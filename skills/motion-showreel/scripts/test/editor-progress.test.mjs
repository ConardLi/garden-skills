const S = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let browser;
before(async () => { browser = await launch(await loadChromium(S)); });
after(async () => { await browser?.close(); });
const readState = root => JSON.parse(fs.readFileSync(path.join(root, '.showreel-progress/status.json')));
function rootFor(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'showreel-progress-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true })); return root;
}
function scene(root, color = '#4678ac') {
  fs.writeFileSync(path.join(root, 'editor.json'), JSON.stringify({ duration: 1, size: '320x180', tracks: [{ id: 'bgm', kind: 'bgm', file: 'tone.wav' }] }));
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=1', path.join(root, 'tone.wav')]);
  fs.writeFileSync(path.join(root, 'index.html'), `<!doctype html><style>body{margin:0}</style><canvas width="320" height="180"></canvas><script>window.DUR=1;window.READY=true;window.render=t=>{window.lastRendered=t;const g=document.querySelector('canvas').getContext('2d');g.fillStyle='${color}';g.fillRect(0,0,320,180);g.fillStyle='#fff';g.fillRect(20+t*80,40,30,30)};window.render(0)</script>`);
}
function assertNoMP4(root) {
  const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(f => f.isDirectory() ? walk(path.join(dir, f.name)) : [f.name]);
  assert.equal(walk(root).some(name => name.endsWith('.mp4')), false);
}

test('an empty project exposes real stage counts without requiring production specifications or starting media work', async t => {
  const root = rootFor(t), app = await createProgressServer(root);
  t.after(() => app.close());
  let state = await (await fetch(new URL('/api/progress', app.url))).json();
  assert.equal(state.preview, null); assert.equal(state.stages.length, 6);
  const bootstrap = await (await fetch(new URL('/api/project', app.url))).json();
  assert.equal(bootstrap.project, null);
  assert.equal(bootstrap.progressURL, new URL('/api/progress', app.url).href);
  const shell = await (await fetch(app.url)).text();
  assert.equal((shell.match(/<iframe\b/g) || []).length, 1, 'the empty and finished workspaces share one shell with only the scene iframe');
  assert.match(shell, /__showreel-editor\/editor\.js/);
  assert.equal(fs.existsSync(path.join(root, 'index.html')), false);
  updateProgress(root, { stage: 'scenes', done: 2, total: 8, message: '两个镜头已完成' });
  state = await (await fetch(new URL('/api/progress', app.url))).json();
  assert.equal(state.stages.find(s => s.id === 'scenes').done, 2);
  updateProgress(root, { stage: 'scenes', message: '继续制作第三个镜头' });
  assert.equal(readState(root).stages.find(s => s.id === 'scenes').done, 2);
  assert.throws(() => updateProgress(root, { stage: 'scenes', done: 9, total: 8 }), /counts/);
  assert.throws(() => updateProgress(root, { stage: 'unknown' }), /known stage/);
  assertNoMP4(root);
});

test('stage images and audio are immutable, project-local, and support byte-range playback', async t => {
  const root = rootFor(t), app = await createProgressServer(root);
  t.after(() => app.close()); scene(root);
  const original = fs.readFileSync(path.join(root, 'tone.wav'));
  await publishArtifact(root, 'tone.wav', { stage: 'narration', message: '口播样例' });
  const artifact = readState(root).artifacts[0]; fs.writeFileSync(path.join(root, 'tone.wav'), 'later unfinished edit');
  const response = await fetch(new URL(artifact.url, app.url), { headers: { Range: 'bytes=0-31' } });
  assert.equal(response.status, 206); assert.deepEqual(Buffer.from(await response.arrayBuffer()), original.subarray(0, 32));
  await assert.rejects(publishArtifact(root, '../outside.wav', { stage: 'narration' }), /relative path/);
  assertNoMP4(root);
});

test('published snapshots preserve the last working scene, reject early export and audio edits, and unlock only final review', async t => {
  const root = rootFor(t), app = await createProgressServer(root);
  t.after(() => app.close()); scene(root);
  fs.writeFileSync(path.join(root, '.env'), 'SECRET=never-copy');
  await publishPreview(root, '.', { stage: 'scenes', fps: 10 });
  const first = readState(root).preview;
  assert.equal(readState(root).stages.find(s => s.id === 'scenes').status, 'running', 'a playable work in progress does not claim the production stage is complete');
  assert.equal(fs.existsSync(path.join(root, first.directory, '.env')), false);
  let state = await (await fetch(new URL('/api/progress', app.url))).json();
  const childURL = state.preview.url;
  const data = await (await fetch(new URL('/api/project', childURL))).json();
  assert.equal(data.project.canExport, false); assert.equal(data.project.readOnly, true);
  assert.equal(data.progressURL, new URL('/api/progress', app.url).href);
  assert.equal(data.progressRevision.id, first.id);
  const childOrigin = new URL(childURL).origin;
  const allowed = await fetch(data.progressURL, { headers: { Origin: childOrigin } });
  assert.equal(allowed.status, 200);
  assert.equal(allowed.headers.get('access-control-allow-origin'), childOrigin);
  assert.equal(allowed.headers.get('vary'), 'Origin');
  const unrelated = await fetch(data.progressURL, { headers: { Origin: 'http://127.0.0.1:9' } });
  assert.equal(unrelated.status, 403);
  assert.equal(unrelated.headers.get('access-control-allow-origin'), null);
  const post = (route, body) => fetch(new URL(route, childURL), { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-showreel-token': data.token }, body: JSON.stringify(body) });
  assert.equal((await post('/api/jobs', { type: 'export', session: data.session })).status, 403);
  data.session.tracks[0].gain = 0.2;
  assert.equal((await post('/api/session', data.session)).status, 403);
  const original = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  fs.writeFileSync(path.join(root, 'index.html'), original.replace('window.render=t=>{', 'window.render=t=>{throw new Error("unfinished scene");'));
  assert.equal(await (await fetch(new URL('/project/index.html', childURL))).text(), original);
  await assert.rejects(publishPreview(root, '.', { stage: 'scenes', fps: 10 }), /unfinished scene/);
  assert.equal(readState(root).preview.id, first.id);
  state = await (await fetch(new URL('/api/progress', app.url))).json();
  assert.equal(state.preview.url, childURL); assert.equal(state.stages.find(s => s.id === 'scenes').status, 'failed');
  fs.writeFileSync(path.join(root, 'index.html'), original);
  await assert.rejects(publishPreview(root, '.', { stage: 'scenes', final: true, fps: 10 }), /review stage/);
  await publishPreview(root, '.', { stage: 'review', final: true, fps: 10, quality: { subframes: 4, dpr: 2, grain: 3 } });
  state = await (await fetch(new URL('/api/progress', app.url))).json();
  const final = await (await fetch(new URL('/api/project', state.preview.url))).json();
  assert.deepEqual(final.quality, { subframes: 4, dpr: 2, grain: 3 }, 'early opening must not lock in default export quality');
  assert.equal(final.project.canExport, true); assert.equal(final.project.readOnly, false);
  assertNoMP4(root);
});

test('one workspace shows stage artifacts, opens scene revisions at top level and retains final edits until a manual switch', async t => {
  const root = rootFor(t), app = await createProgressServer(root);
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  t.after(async () => { await page.close({ runBeforeUnload: false }); await app.close(); });
  await page.goto(app.url); await page.waitForSelector('.stage');
  assert.equal(await page.locator('#placeholder').isVisible(), true);
  assert.equal(await page.locator('#toggle-inspector').isDisabled(), true);
  assert.equal(await page.locator('#reset').isDisabled(), true);
  scene(root);
  const png = await page.screenshot(); fs.writeFileSync(path.join(root, 'style.png'), png);
  await publishArtifact(root, 'style.png', { stage: 'style' });
  await page.locator('#artifact-content img').waitFor();
  await publishArtifact(root, 'tone.wav', { stage: 'narration' });
  await page.waitForFunction(() => document.querySelectorAll('#artifacts button').length === 2);
  const artifactButton = await page.locator('#artifacts button').first().elementHandle();
  await page.waitForTimeout(1200);
  assert.equal(await artifactButton.evaluate(el => el.isConnected), true, 'unchanged polling preserves artifact controls');
  await page.locator('#close-artifact').click();
  await page.setViewportSize({ width: 478, height: 735 });
  await page.locator('#toggle-progress').click();
  const audioArtifact = readState(root).artifacts.at(-1);
  assert.equal(await page.locator(`#artifacts [data-id="${audioArtifact.id}"]`).isVisible(), true);
  await page.locator(`#artifacts [data-id="${audioArtifact.id}"]`).click();
  await page.locator('#artifact-content audio').waitFor();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await publishPreview(root, '.', { stage: 'scenes', fps: 10 });
  await page.waitForURL(url => url.pathname === '/editor');
  await page.waitForFunction(() => window.__showreelEditor?.ready);
  assert.equal(await page.locator('iframe').count(), 1, 'only the actual scene is embedded');
  assert.equal(page.frames().length, 2);
  assert.equal(await page.locator('#export').isDisabled(), true);
  await page.evaluate(() => window.__showreelEditor.seek(0.4));
  assert.equal(await page.evaluate(() => window.__showreelEditor.picture.lastRendered), 0.4);
  await page.locator('#toggle-progress').click();
  await page.getByRole('button', { name: /tone.wav/ }).click();
  await page.locator('#artifact-content audio').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.evaluate(() => window.__showreelEditor.time), 0.4, 'sample keyboard controls must not seek the film behind them');
  await page.keyboard.press('Space');
  assert.equal(await page.locator('#play').getAttribute('aria-label'), '播放', 'sample playback must not start the film');
  await page.locator('#close-artifact').click();
  await publishPreview(root, '.', { stage: 'review', final: true, fps: 10 });
  await page.waitForFunction(() => window.__showreelEditor?.ready && window.__showreelEditor.project.canExport);
  assert.equal(await page.locator('#export').isEnabled(), true);
  assert.equal(await page.locator('#auto').isChecked(), false);
  await page.evaluate(() => window.__showreelEditor.edit(s => { s.tracks[0].gain = 0.42; }));
  await page.evaluate(() => window.__showreelEditor.save());
  const finalURL = page.url();
  scene(root, '#aa7755');
  await publishPreview(root, '.', { stage: 'review', final: true, fps: 10 });
  await page.locator('#switch').waitFor();
  assert.equal(page.url(), finalURL);
  assert.match(await page.locator('#current-stage').textContent(), /新版本可用/);
  assert.equal(await page.evaluate(() => window.__showreelEditor.session.tracks[0].gain), 0.42);
  await page.evaluate(() => window.__showreelEditor.edit(s => { s.tracks[0].gain = 0.27; }));
  await page.locator('#switch').click();
  assert.equal(page.url(), finalURL, 'a requested version switch must wait for unsaved edits');
  assert.match(await page.locator('#progress-message').textContent(), /保存/);
  assert.equal(await page.evaluate(() => window.__showreelEditor.session.tracks[0].gain), 0.27);
  await page.evaluate(() => window.__showreelEditor.save());
  await page.locator('#switch').click();
  await page.waitForURL(url => url.href !== finalURL);
  await page.waitForFunction(() => window.__showreelEditor?.ready);
  assert.equal(await page.locator('iframe').count(), 1);
  assert.equal(await page.evaluate(() => window.__showreelEditor.session.tracks[0].gain), 1);
  assertNoMP4(root);
});

test('shots publish independently before the whole film exists; results, counts and old previews survive failures and retries', async t => {
  const root = rootFor(t), app = await createProgressServer(root);
  t.after(() => app.close());
  const first = path.join(root, 'shots/one'); fs.mkdirSync(first, { recursive: true }); scene(first);
  updateProgress(root, { stage: 'scenes', done: 0, total: 3 });
  await publishPreview(root, 'shots/one', { stage: 'scenes', shot: 'one', name: '镜头1：种子', total: 3, fps: 10 });
  let state = readState(root), old = state.preview;
  assert.equal(fs.existsSync(path.join(root, 'index.html')), false, 'no assembled film is needed');
  assert.equal(state.shots.length, 1); assert.equal(state.stages.find(s => s.id === 'scenes').done, 1);
  assert.equal(state.stages.find(s => s.id === 'scenes').status, 'running');
  const second = path.join(root, 'shots/two'); fs.mkdirSync(second); scene(second, '#aa6633');
  await publishPreview(root, 'shots/two', { stage: 'scenes', shot: 'two', name: '镜头2：展开', total: 3, fps: 10 });
  state = readState(root); assert.equal(state.shots.length, 2); assert.equal(state.stages.find(s => s.id === 'scenes').done, 2);
  const latest = state.preview.id;
  const history = await (await fetch(new URL(`/api/preview/${old.id}`, app.url))).json();
  assert.equal(history.id, old.id);
  assert.equal((await (await fetch(new URL('/api/project', history.url))).json()).project.canExport, false);
  assert.equal(readState(root).preview.id, latest, 'browsing a previous shot must not change the latest production version');
  fs.writeFileSync(path.join(second, 'index.html'), '<script>throw new Error("unfinished second shot")</script>');
  await assert.rejects(publishPreview(root, 'shots/two', { stage: 'scenes', shot: 'two', total: 3, fps: 10 }));
  assert.equal(readState(root).shots.length, 2); assert.equal(readState(root).preview.id, latest);
  scene(first, '#228855');
  await publishPreview(root, 'shots/one', { stage: 'scenes', shot: 'one', name: '镜头1修订', total: 3, fps: 10 });
  assert.equal(readState(root).shots.length, 2, 'revising one shot cannot inflate completed counts');
  assert.deepEqual(readState(root).shots.map(s => s.id), ['one', 'two'], 'revising a shot preserves the presentation order');
  fs.writeFileSync(path.join(root, 'brief.md'), '真实脚本结果\n<script>unsafe()</script>');
  await publishArtifact(root, 'brief.md', { stage: 'brief', name: '需求与分镜' });
  const page = await browser.newPage({ viewport: { width: 478, height: 800 } });
  t.after(() => page.close({ runBeforeUnload: false }));
  await page.goto(app.url); await page.waitForFunction(() => window.__showreelEditor?.ready);
  await page.locator('#toggle-progress').click();
  const spinning = await page.locator('[data-stage="scenes"] .stage-icon').evaluate(el => getComputedStyle(el).animationName);
  assert.equal(spinning, 'progress-spin');
  assert.equal(await page.locator('[data-stage="scenes"] button').count(), 0, 'the progress panel contains no shot browser');
  assert.equal(await page.locator('#shot-picker option[data-shot]').count(), 2);
  assert.match(await page.locator('[data-stage="scenes"] .stage-count').textContent(), /2 \/ 3/);
  await page.getByRole('button', { name: /需求与分镜/ }).click();
  await page.waitForFunction(() => document.querySelector('.document-result')?.textContent.includes('<script>'));
  assert.equal(await page.locator('#artifact-content script').count(), 0, 'text results are never executed');
  await page.locator('#close-artifact').click(); await page.locator('#toggle-progress').click();
  await page.locator('#close-progress').click();
  await page.locator('#shot-picker').selectOption({ label: '镜头2：展开' });
  await page.waitForFunction(() => window.__showreelEditor?.ready && document.getElementById('stage-label').textContent.includes('镜头2'));
  assert.equal(await page.locator('#auto').isChecked(), false, 'browsing previous work must not immediately jump to the newest revision');
  await page.locator('#toggle-progress').click();
  assert.equal(await page.locator('[data-stage="scenes"] button').count(), 0, 'the progress panel contains no shot browser');
  assert.equal(await page.locator('#shot-picker option[data-shot]').count(), 2);
  await page.locator('#close-progress').click();
  await page.locator('#shot-picker').selectOption({ label: '镜头2：展开' });
  await page.waitForFunction(() => document.getElementById('play').getAttribute('aria-label') === '暂停');
  assert.equal(await page.locator('#progress-panel').isVisible(), false, 'the current shot result directly replays the shot');
  assertNoMP4(root);
});
